export function hasMealPhoto(recipe: { id: string; image?: string | null }): boolean {
  return Boolean(
    MEAL_PHOTO_BY_RECIPE_ID[recipe.id] ||
      (recipe.image && recipe.image.includes('/images/meals/') && recipe.image.endsWith('.jpg')),
  )
}

export function recipeImage(recipe: { id: string; image?: string | null; category?: string }): string {
  if (MEAL_PHOTO_BY_RECIPE_ID[recipe.id]) {
    return asset(MEAL_PHOTO_BY_RECIPE_ID[recipe.id])
  }
  if (recipe.image && recipe.image.includes('/images/meals/') && recipe.image.endsWith('.jpg')) {
    return asset(recipe.image)
  }
  if (recipe.image) {
    return asset(recipe.image)
  }
  return asset('/images/cover.jpg')
}
